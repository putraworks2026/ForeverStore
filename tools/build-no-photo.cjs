/* Derives tools/no-photo.json from tools/product-photo-sources.json.
 * Run from the repo root:  node tools/build-no-photo.cjs
 *
 * product-photo-sources.json is the single hand-maintained list. This script only
 * projects the products whose image is a locally rendered tile (placeholder: true),
 * so the catalogue can flag them and no second list is edited by hand.
 */
const fs = require("fs");
const path = require("path");

const src = JSON.parse(fs.readFileSync(path.join("tools", "product-photo-sources.json"), "utf8"));
const ids = src.images.filter((i) => i.placeholder === true).map((i) => i.slug).sort();

fs.writeFileSync(
  path.join("tools", "no-photo.json"),
  JSON.stringify(
    {
      note: "GENERATED by tools/build-no-photo.cjs from tools/product-photo-sources.json. Products whose image is a rendered tile, not photography.",
      ids: ids
    },
    null,
    1
  ) + "\n"
);
console.log("no-photo.json: " + ids.length + " rendered tiles -> " + ids.join(", "));
