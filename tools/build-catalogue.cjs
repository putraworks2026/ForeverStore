/* Builds assets/data/products.js from the retail price list and the catalogue map.
 * Run from the repo root:  node tools/build-catalogue.cjs
 *
 * Every price comes from assets/data/price-list.json (SRP, GST included); every
 * name, category and pack form comes from tools/catalogue-map.json. Nothing here
 * invents a product or a figure. Products in the map but not in the price list
 * stay available:false with no price.
 */
const fs = require("fs");
const path = require("path");

const root = process.cwd();
const priceList = JSON.parse(fs.readFileSync(path.join(root, "assets/data/price-list.json"), "utf8"));
const map = JSON.parse(fs.readFileSync(path.join(root, "tools/catalogue-map.json"), "utf8"));

const prices = new Map(priceList.items.map((x) => [x.code, x.priceInclGst]));
const CATS = ["Packs", "Drinks", "Shakes", "Bee products", "Skincare", "Personal care", "Supplements"];

const imgDir = path.join(root, "assets/img");
const products = map.items.map((m) => {
  const price = prices.has(m.code) ? prices.get(m.code) : null;
  const bespoke = fs.existsSync(path.join(imgDir, m.id + ".svg"));
  return {
    id: m.id,
    name: m.name,
    category: m.category,
    form: m.form,
    sku: m.code,
    img: bespoke ? "assets/img/" + m.id + ".svg" : "assets/img/form-" + m.form + ".svg",
    available: price != null,
    price: price
  };
});

const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
const out = [];
out.push("/**");
out.push(" * ForeverStore product catalogue. GENERATED by tools/build-catalogue.cjs.");
out.push(" *");
out.push(" * Prices come from assets/data/price-list.json, the Singapore retail price list");
out.push(" * (SRP), and INCLUDE 9% GST. `sku` is the Forever Living order code.");
out.push(" * Volumes, ingredient lists and usage are not stored here: they live in");
out.push(" * assets/data/details.js, each entry citing the fact sheet it was taken from.");
out.push(" */");
out.push("window.PRODUCTS = [");

for (let c = 0; c < CATS.length; c++) {
  const cat = CATS[c];
  const group = products.filter((p) => p.category === cat);
  if (!group.length) continue;
  out.push("  // ---------- " + cat + " ----------");
  group.forEach((p, i) => {
    out.push("  {");
    out.push('    id: "' + p.id + '",');
    out.push('    name: "' + esc(p.name) + '",');
    out.push('    category: "' + esc(p.category) + '",');
    out.push('    form: "' + p.form + '",');
    out.push('    sku: "' + p.sku + '",');
    out.push('    img: "' + p.img + '",');
    out.push("    available: " + p.available + ",");
    out.push("    price: " + (p.price == null ? "null" : p.price));
    const lastInGroup = i === group.length - 1;
    const lastCat = c === CATS.length - 1 || products.every((x) => x.category !== CATS[c + 1]);
    out.push("  }" + (lastInGroup && lastCat ? "" : ","));
  });
}
out.push("];");
out.push("");
out.push("window.CATEGORIES = " + JSON.stringify(CATS.filter((c) => products.some((p) => p.category === c))) + ";");
out.push("");

fs.writeFileSync(path.join(root, "assets/data/products.js"), out.join("\n"));
const priced = products.filter((p) => p.available).length;
console.log("products: " + products.length + " | priced: " + priced + " | unpriced: " + (products.length - priced));
